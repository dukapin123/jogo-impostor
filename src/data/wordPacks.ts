// Mapeamento dinâmico para os componentes do jogo
export const WORD_CATEGORIES: WordCategory[] = Object.entries(BANCO_DE_PALAVRAS).map(
  ([catKey, items]) => ({
    id: catKey.toLowerCase(),
    name: catKey,
    iconName: catKey,
    description: `Tema: ${catKey}`,
    words: items.map((item, idx) => ({
      id: `${catKey.toLowerCase()}_${idx}_${item.palavra.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')}`,
      word: item.palavra,
      hint: item.dica,
    })),
  })
);

export const ALL_WORDS = WORD_CATEGORIES.flatMap((category) =>
  category.words.map((item) => ({
    ...item,
    category: category.name,
    categoryId: category.id,
  }))
);
